"""Fine-tuning micropattern NCAs: parent checks and writing fine-tune sweeps.

A fine-tune run starts from the weights of a trained **parent** bundle
(``initialization.model_id``). For that to make sense the child must read the
data exactly as the parent did. ``check_parent_compatible`` lists every
setting that differs; ``Experiments/micropatterns/train.py`` stops a run that
has any.

``write_finetune_sweep`` turns a template sweep plus a list of parents (a
registry selection) into an ordinary sweep file. Each parent becomes one row
of a zipped ``groups:`` block that copies the parent's settings, so nothing is
typed in by hand. Then generate the manifest from that file as usual.

Command line::

    python -m Experiments.micropatterns.finetune <template.yaml> \\
        --selection <selection.yaml> --out <sweep.yaml> [--total-iterations N]

The tutorial ``demo/finetuning_workflow.py`` walks through the whole workflow.
"""

from __future__ import annotations

import argparse
import tempfile
from dataclasses import fields, is_dataclass
from datetime import date
from enum import Enum
from pathlib import Path
from typing import Any, Iterable, Mapping

from omegaconf import OmegaConf

# Placeholder for initialization.model_id in a template sweep. A template
# generated by mistake stops at the registry lookup instead of quietly
# training from scratch.
FROM_PARENTS = "FROM_PARENTS"

# Settings the child must share with its parent: model architecture and
# everything that changes how the images are read, cleaned and normalised.
# Sections (model, cleaning) are copied field by field.
PARENT_SETTINGS = (
    "model",
    "data.dataset",
    "data.downsample",
    "data.micropattern.projection",
    "data.micropattern.cleaning",
    "data.micropattern.excluded_measurements",
    "data.micropattern.experiment_groups",
    "data.micropattern.data_channels",
    "data.micropattern.timesteps",
    "data.micropattern.histogram_percentiles",
    "data.micropattern.intensity_factors",
    "data.micropattern.train_replicates",
    "data.micropattern.validation_replicates",
    "run.t",
)

# Copied from the parent only when the template does not set them.
PARENT_DEFAULTS = ("run.repeat",)


# ---------------------------------------------------------------------------
# Parent checks
# ---------------------------------------------------------------------------

def _plain(value: Any) -> Any:
    """Config value -> plain YAML value (lists, dicts, strings, numbers)."""
    if is_dataclass(value):
        return {item.name: _plain(getattr(value, item.name)) for item in fields(value)}
    if isinstance(value, Enum):
        return value.value
    if isinstance(value, Path):
        return str(value)
    if isinstance(value, Mapping):
        return {str(key): _plain(item) for key, item in value.items()}
    if isinstance(value, (list, tuple)):
        return [_plain(item) for item in value]
    return value


def _get(config: Any, dotted_key: str) -> Any:
    for part in dotted_key.split("."):
        config = getattr(config, part)
    return config


def _comparable_model(model_config) -> dict:
    # Archived SYCL families (e.g. gNCA_sycl) load as their portable
    # equivalents (gNCA), so treat the two names as the same model.
    from NCA.model.factory import portable_family

    values = _plain(model_config)
    values["family"] = portable_family(values["family"])
    return values


def check_parent_compatible(parent_config, child_config) -> list[str]:
    """Reasons the child run cannot start from the parent (empty if it can).

    Both arguments are typed experiment configs (``bundle.config`` and the
    run's config).
    """
    from Common.dataloader.micropattern_schemas import MICROPATTERN_260726_SCHEMA

    problems = []
    if _comparable_model(parent_config.model) != _comparable_model(child_config.model):
        problems.append("the model settings (model.*) differ")

    parent_data = parent_config.data
    child_data = child_config.data
    all_groups = MICROPATTERN_260726_SCHEMA.group_names
    parent_groups = parent_data.micropattern.experiment_groups or all_groups
    child_groups = child_data.micropattern.experiment_groups or all_groups
    if (
        parent_data.dataset != "micropatterns_260726"
        or child_data.dataset != "micropatterns_260726"
        or set(parent_groups) != set(all_groups)
        or tuple(parent_groups) != tuple(child_groups)
    ):
        problems.append(
            "fine-tuning requires micropatterns_260726 parent and child "
            "configurations with every experiment group"
        )

    parent_excluded = parent_data.micropattern.excluded_measurements
    child_excluded = child_data.micropattern.excluded_measurements
    if set(parent_excluded) != set(child_excluded):
        problems.append(
            f"the parent left out the channels {list(parent_excluded)}, but this "
            f"run leaves out {list(child_excluded)}; train a parent with the "
            "same data.micropattern.excluded_measurements"
        )
    if parent_data.micropattern.projection != child_data.micropattern.projection:
        problems.append(
            f"the parent was trained on {parent_data.micropattern.projection} "
            f"projections, but this run uses {child_data.micropattern.projection}"
        )

    same_settings = {
        "data.downsample": "resolution",
        "data.micropattern.cleaning": "image cleaning",
        "data.micropattern.timesteps": "observation times",
        "data.micropattern.histogram_percentiles": "intensity normalisation",
        "data.micropattern.intensity_factors": "intensity normalisation",
        # The normalisation is fitted on the training replicates, and the
        # parent's training replicates must not become validation data.
        "data.micropattern.train_replicates": "training replicates",
        "run.t": "NCA steps per observation interval",
    }
    for key, meaning in same_settings.items():
        parent_value = _plain(_get(parent_config, key))
        child_value = _plain(_get(child_config, key))
        if parent_value != child_value:
            problems.append(f"{key} ({meaning}) differs: {_difference(parent_value, child_value)}")
    return problems


def _difference(parent_value, child_value) -> str:
    """Short description of how two values differ (only the differing entries of dicts)."""
    if isinstance(parent_value, dict) and isinstance(child_value, dict):
        missing = object()
        return ", ".join(
            f"{name}: parent {parent_value.get(name, '<unset>')!r}, "
            f"this run {child_value.get(name, '<unset>')!r}"
            for name in dict.fromkeys([*parent_value, *child_value])
            if parent_value.get(name, missing) != child_value.get(name, missing)
        )
    return f"parent {parent_value!r}, this run {child_value!r}"


# ---------------------------------------------------------------------------
# Writing fine-tune sweeps
# ---------------------------------------------------------------------------

def _leaf_settings(config, dotted_key: str) -> dict[str, Any]:
    """Dotted keys and plain values for one setting; sections become their fields."""
    value = _get(config, dotted_key)
    if not is_dataclass(value):
        return {dotted_key: _plain(value)}
    leaves = {}
    for item in fields(value):
        leaves.update(_leaf_settings(config, f"{dotted_key}.{item.name}"))
    return leaves


def parent_overrides(bundle, keys: Iterable[str] = PARENT_SETTINGS) -> dict[str, Any]:
    """Sweep overrides that make a child read the data as ``bundle`` did."""
    from NCA.model.factory import portable_family

    overrides = {"initialization.model_id": bundle.id}
    for key in keys:
        overrides.update(_leaf_settings(bundle.config, key))
    if "model.family" in overrides:
        overrides["model.family"] = portable_family(overrides["model.family"])
    return overrides


def _sweep_keys(sweep: Mapping[str, Any]) -> set[str]:
    """Every dotted key a sweep sets in its grid, groups or branches."""
    from Experiments.config_workflow import flatten_grid

    keys = {key for key, _ in flatten_grid(dict(sweep.get("grid") or {}))}
    for group in sweep.get("groups") or []:
        keys.update(key for key, _ in flatten_grid(dict(group)))
    for branch in sweep.get("branches") or []:
        keys.update(_sweep_keys(branch))
    return keys


def _overlaps(key: str, other: str) -> bool:
    return key == other or key.startswith(other + ".") or other.startswith(key + ".")


def finetune_sweep(
    template: Mapping[str, Any],
    parents: Iterable,
    *,
    total_iterations: int | None = None,
) -> dict[str, Any]:
    """The template sweep with one zipped ``groups:`` row per parent bundle.

    With ``total_iterations`` each child trains for ``total_iterations`` minus
    its parent's ``run.iterations``, so parent and child together use a fixed
    budget.
    """
    sweep = OmegaConf.to_container(OmegaConf.create(dict(template)), resolve=False)
    grid = dict(sweep.get("grid") or {})
    if grid.pop("initialization.model_id", [FROM_PARENTS]) != [FROM_PARENTS]:
        raise ValueError(
            f"The template must set initialization.model_id: [{FROM_PARENTS}]"
        )
    sweep["grid"] = grid
    template_keys = _sweep_keys(sweep)

    rows = []
    for bundle in parents:
        overrides = parent_overrides(bundle)
        for key in PARENT_DEFAULTS:
            if key not in template_keys and _get(bundle.config, key) is not None:
                overrides[key] = _plain(_get(bundle.config, key))
        if total_iterations is not None:
            remaining = int(total_iterations) - int(bundle.config.run.iterations)
            if remaining <= 0:
                raise ValueError(
                    f"Parent {bundle.id} already trained for "
                    f"{bundle.config.run.iterations} iterations, which uses up "
                    f"the budget of {total_iterations}"
                )
            overrides["run.iterations"] = remaining
        rows.append(overrides)
    if not rows:
        raise ValueError("No parent models given")

    conflicts = sorted(
        {key for key in template_keys for row in rows for other in row if _overlaps(key, other)}
    )
    if conflicts:
        raise ValueError(
            "The template sets values that come from the parent models; "
            f"remove them from the template: {conflicts}"
        )
    keys = list(dict.fromkeys(key for row in rows for key in row))
    if any(set(row) != set(keys) for row in rows):
        raise ValueError("The parents do not all have the same settings")
    block = {key: [row[key] for row in rows] for key in keys}
    sweep["groups"] = [*(sweep.get("groups") or []), block]
    return sweep


def check_finetune_sweep(sweep: Mapping[str, Any], base_config: str | Path, parents) -> int:
    """Expand the sweep on the base config and check every run against its parent.

    Returns the number of runs. Raises ``ValueError`` naming the first run
    that does not fit its parent.
    """
    from Experiments.config import load_experiment_config
    from Experiments.config_workflow import generate_manifest, load_yaml

    by_id = {bundle.id: bundle for bundle in parents}
    with tempfile.TemporaryDirectory() as folder:
        manifest = generate_manifest(load_yaml(base_config), dict(sweep), Path(folder))
    for entry in manifest["configs"]:
        config = load_experiment_config(entry["config"])
        parent = by_id[config.initialization.model_id]
        problems = check_parent_compatible(parent.config, config)
        if problems:
            raise ValueError(
                f"Run {entry['index']} does not fit its parent {parent.id}: "
                + "; ".join(problems)
            )
    return manifest["count"]


def write_finetune_sweep(
    template_path: str | Path,
    parent_ids: Iterable[str],
    registry,
    out_path: str | Path,
    *,
    base_config: str | Path = "Experiments/micropatterns/conf/base_config.yaml",
    total_iterations: int | None = None,
    note: str = "",
) -> dict[str, Any]:
    """Write a fine-tune sweep for ``parent_ids`` and check every run.

    ``registry`` is a ``ModelRegistry``. Returns the sweep (as a dict).
    """
    template_path = Path(template_path)
    parents = [registry.get(model_id) for model_id in parent_ids]
    sweep = finetune_sweep(
        OmegaConf.to_container(OmegaConf.load(template_path), resolve=False),
        parents,
        total_iterations=total_iterations,
    )
    count = check_finetune_sweep(sweep, base_config, parents)
    header = [
        f"# Written by Experiments/micropatterns/finetune.py on {date.today()}",
        f"# from the template {template_path.as_posix()}",
        f"# with {len(parents)} parent model(s) and {count} run(s).",
    ]
    if total_iterations is not None:
        header.append(f"# Parent plus child iterations: {total_iterations}.")
    if note:
        header.extend(f"# {line}" for line in note.splitlines())
    header.append("# Don't edit the groups block by hand; write the file again instead.")
    out_path = Path(out_path)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(
        "\n".join(header) + "\n" + OmegaConf.to_yaml(OmegaConf.create(sweep)),
        encoding="utf-8",
    )
    return sweep


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("template", help="Template sweep with initialization.model_id: [FROM_PARENTS]")
    parser.add_argument("--selection", required=True, help="Registry selection listing the parents")
    parser.add_argument("--out", required=True, help="Sweep file to write")
    parser.add_argument(
        "--base-config", default="Experiments/micropatterns/conf/base_config.yaml"
    )
    parser.add_argument("--total-iterations", type=int, default=None)
    parser.add_argument(
        "--model-store-root", default=None, help="Defaults to MODEL_STORE_ROOT"
    )
    args = parser.parse_args(argv)

    from dotenv import load_dotenv

    from Experiments.model_registry import ModelRegistry, load_selection

    load_dotenv()
    registry = (
        ModelRegistry(args.model_store_root)
        if args.model_store_root
        else ModelRegistry.from_env()
    )
    parent_ids = [record["model_id"] for record in load_selection(args.selection)]
    write_finetune_sweep(
        args.template,
        parent_ids,
        registry,
        args.out,
        base_config=args.base_config,
        total_iterations=args.total_iterations,
        note=f"Parents: {Path(args.selection).as_posix()}",
    )
    print(f"Wrote {args.out}. Next:")
    print(
        f"  python Experiments/generate_configs.py {args.out} "
        f"{args.base_config} <conf/generated folder>"
    )


if __name__ == "__main__":
    main()
